"""Счётчики попыток пазла и журнал попыток (JSONL).

Состояние — процесс-локал (list как изменяемый синглтон), поэтому reset()
работает между тестами и воркерами. Журнал _attempt — машиночитаемый
пер-попыточный след для классификации fail-reason (detect/drag/token/UI),
пишется в $TMP, в репозиторий не попадает.

Инвариант KPI (ADR §14.7): failures() + solved == attempts().

Перенесено из puzzle.py без изменения кода (механический сплит).
"""

import json
import os
import tempfile
import time
from datetime import datetime

import numpy as np


# Сколько попыток решения даёт воркер на один инцидент пазла, прежде чем
# признать его нерешаемым (fallback → FAB-reload → FSM).
#
# 2026-09-22 live (2467 записей): drag идеален (445/517 с |err|≤0.9), но
# детектор даёт неверный bx в ~97% точных дропов → свип ±3 бесполезен
# (капча рероллится после каждого дропа). Успехи приходят из ПОВТОРНЫХ
# независимых заходов (свежий захват кадра → новые кандидаты): 2 захода
# давали ~15/492 ок. attempts=3 даёт ~1.5x шансов без риска свипа.
PUZZLE_MAX_ATTEMPTS = 3

# Бюджет времени на ОДНО решение пазла (все попытки и кандидаты вместе).
# Дефолт БЕЗОПАСНЫЙ и живёт здесь, а не в аргументе вызова: иначе вызывающий
# должен вспомнить про него, и забывший получает бесконечный свип.
#
# Замер 2026-10-02 (живой лог prezervativy). Нормативная попытка: 10 с, 17
# шагов, err < 1 px. Но иногда CDP-шаги встают: 11 с между соседними шагами
# вместо 0.4 с (в 25 раз медленнее), и одна попытка растягивалась на 178 с;
# три попытки — 9 минут на один товар.
#
# Гипотезы, отпавшие по замерам:
#   * базовый Playwright на этой машине: evaluate 1.4 мс, 10 x mouse.move 61 мс
#     (about:blank) и 1.0 мс на живой странице «Antibot Challenge Page»;
#   * боевой профиль Ozon, живая вкладка товара: evaluate 0.9 мс (медиана);
#   * видимость вкладки: 86 проб телеметрии, все state=visible.
# Ни машина, ни профиль, ни страница, ни фон вкладки не медленные — медленной
# делается конкретная вкладка в конкретный момент.
#
# Лог показывает, что лечится сменой вкладки, а не упорством солвера:
#   17:13:17-17:15:49  провал, 15 шагов по 11 с = 178 с, verdict=no
#   17:16:14            FAB-reload, «пазл не решён → ждём заглушку»
#   17:16:27            new_page
#   17:16:45-17:16:55  та же капча (bx=335), 17 шагов, 10 с, verdict=done
# Через 38 с после провала та же капча решилась за 10 секунд просто на новой
# вкладке. Без бюджета солвер продолжал драг в зависшей вкладке вместо того,
# чтобы отдать товар в лестницу восстановления (FAB-reload → new_tab →
# recycle), где new_tab как раз и снимает проблему.
#
# 60 с: нормативный случай укладывается в 30 с (3 кандидата x 10 с), то есть
# запас 2x — успешные попытки не съедаются, а зависшая вкладка отпускается
# более чем вдвое быстрее прежнего.
PUZZLE_BUDGET_S = 60.0

# Процесс-локал (list как изменяемый синглтон, чтобы reset() работал в тестах).
_PUZZLE_FAILURES: list[int] = [0]
_PUZZLE_ATTEMPTS: list[int] = [0]
# Итоги сессии для одной сводной строки в логе. Без них по логу видно только
# отдельные провалы, но не «сколько вообще капч и какой у них итог»: за день
# в логе был 21 отказ и 1 успех, и эти числа нигде не стояли рядом.
_PUZZLE_SOLVED: list[int] = [0]
_PUZZLE_STORMS: list[int] = [0]


def note_solved() -> None:
    _PUZZLE_SOLVED[0] += 1


def solved() -> int:
    """Число УСПЕШНЫХ попыток решения пазла в текущем сборе.

    Инвариант: attempts() == failures() + solved(). Раньше успехи в KPI выводились
    как attempts - failures, то есть успех был ВЫЧИСЛЯЕМОЙ величиной, а не
    измеренной: рассинхрон счётчиков тихо портил бы долю успеха в отчёте.
    Теперь успех считается явно, а search.py проверяет инвариант в рантайме.
    """
    return _PUZZLE_SOLVED[0]


def note_storm() -> None:
    _PUZZLE_STORMS[0] += 1


def summary() -> str:
    """Сводка по пазлам текущего сбора одной строкой — для лога и разбора.

    Формат: `пазлов: попыток=7 решено=2 штормов=1 доля=29%`. Доля считается по
    ПОПЫТКАМ, а не по пазлам: попытка и пазл — разные единицы (PUZZLE_MAX_ATTEMPTS
    попыток на один вызов solve_puzzle), и раньше эти два числа в логе не
    разделялись.
    """
    att = attempts()
    solved = _PUZZLE_SOLVED[0]
    # max() по попыткам: solved инкрементируется в ветках успеха, которые
    # всегда идут после _note_attempt(), но если порядок поменяется, сводка
    # обязана показать согласованные числа, а не «решено=1, попыток=0».
    shown = max(att, solved)
    rate = (solved / shown) if shown else 0.0
    return (f"пазлов: попыток={shown} решено={solved} "
            f"штормов={_PUZZLE_STORMS[0]} доля={rate:.0%}")


def reset() -> None:
    """Сбросить счётчик неудач (вызывается при старте сбора/воркера)."""
    _PUZZLE_FAILURES[0] = 0
    _PUZZLE_ATTEMPTS[0] = 0
    _PUZZLE_SOLVED[0] = 0
    _PUZZLE_STORMS[0] = 0


def failures() -> int:
    """Число неудачных попыток решения пазла в текущем сборе."""
    return _PUZZLE_FAILURES[0]


def attempts() -> int:
    """Число попыток решения пазла (успешных + неудачных) в текущем сборе.

    Счётчик растёт ОДИН раз на каждый заход solve_puzzle (в начале цикла
    попыток), а заход заканчивается либо note_solved(), либо failures += 1.
    Поэтому в бою выполняется attempts == failures + solved, и search.py
    проверяет это в рантайме — но проверяет только НЕВОЗМОЖНЫЕ состояния
    (solved/failures > attempts), потому что юнит-тесты подставляют счётчики
    напрямую. Нужен для solve-rate в KPI (ADR §14.7): без него видно только
    «сорвалось N раз», но не «из скольких».
    """
    return _PUZZLE_ATTEMPTS[0]


def _note_attempt() -> None:
    _PUZZLE_ATTEMPTS[0] += 1


# Куда писать пер-попыточный JSONL (машиночитаемо, для классификации
# fail-reason: detect/drag/token/UI). Диагностика, НЕ в репозиторий.
_ATTEMPT_LOG_DIR = os.environ.get(
    "OZON_ATTEMPT_LOG", os.path.join(tempfile.gettempdir(), "puzzle_attempts"))


def _attempt(kind: str, **kw) -> None:
    """Дописать строку JSONL с попыткой решения (тихая, без исключений)."""

    def _js_default(o):
        if isinstance(o, np.floating):
            return round(float(o), 3)
        if isinstance(o, np.integer):
            return int(o)
        if isinstance(o, np.bool_):
            return bool(o)
        return str(o)

    try:
        os.makedirs(_ATTEMPT_LOG_DIR, exist_ok=True)
        path = os.path.join(_ATTEMPT_LOG_DIR,
                            time.strftime("%Y%m%d") + ".jsonl")
        rec = {"ts": datetime.now().strftime("%H%M%S.%f")[:-3], "kind": kind}
        rec.update(kw)
        with open(path, "a", encoding="utf-8") as f:
            f.write(json.dumps(rec, ensure_ascii=False,
                               default=_js_default) + "\n")
    except Exception:
        pass
